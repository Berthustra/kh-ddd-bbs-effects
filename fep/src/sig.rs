/// Parameter block size of a command id (bytes), from the table. The `_plus` classes (152..155)
/// have all-zero records: their blocks are the base class's layout plus a trailing field, so we
/// give the smallest room any of their blocks has game-wide (docs/fep/structure.md section 4:
/// 0x20 / 0x118 / 0x1c / 0x4c; base layouts 0x1f / 0x115 / 0x1a / 0x4b).
pub fn param_size(id: u16) -> usize {
    match id {
        152 => 0x20,
        153 => 0x118,
        154 => 0x1c,
        155 => 0x4c,
        _ => TABLE.get(id as usize).map_or(0, |r| u16::from_le_bytes([r[4], r[5]]) as usize),
    }
}

/// Work size of a command id in bytes (the table's 2-byte units, doubled). 0 for the `_plus`
/// classes, which still use work (their parts reserve it: the part's own work size covers them).
pub fn work_size(id: u16) -> usize {
    TABLE.get(id as usize).map_or(0, |r| u16::from_le_bytes([r[6], r[7]]) as usize * 2)
}

/// Name of a command id (`"?"` past the table).
pub fn name(id: u16) -> &'static str {
    NAMES.get(id as usize).copied().unwrap_or("?")
}
